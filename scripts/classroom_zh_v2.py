def assignments(players,mission):
    """One explicit assignment per person; every required role covered each round."""
    slots={2:['朗读＋记录','操作＋核查'],3:['朗读','操作','记录＋核查'],4:ROLES,
           5:['朗读','朗读','操作','记录','核查'],6:['朗读','朗读','操作','操作','记录','核查']}[players]
    return [slots[(person-(mission-1))%players] for person in range(players)]

def rotation_table(players):
    return grid(['关卡']+[f'玩家{i}' for i in range(1,players+1)],
                [[str(m)]+assignments(players,m) for m in range(1,6)],row_height=35)

def steps(values):
    return text('<br/>'.join(f'{i}. {value}' for i,value in enumerate(values,1)))

