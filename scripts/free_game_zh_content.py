def P(title, intro='', *blocks):
    return dict(title=title, intro=intro, blocks=list(blocks))

def text(value): return ('text', value)
def box(title, value): return ('box', title, value)
def grid(heads, rows, **kw):
    if heads[0] in ['玩家人数','每组人数']: kw.setdefault('ratios',[.17,.83])
    return ('table', heads, rows, kw)
def cards(items, columns=2, height=95, **kw): return ('cards', items, columns, height, kw)
def lines(labels): return ('lines', labels)
def special(name): return ('special', name)

